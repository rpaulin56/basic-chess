/**
 * Il francese.
 *
 * Tradotto dall'italiano (l'inglese come secondo parere), e pensato per essere RIVISTO
 * da una madrelingua, non preso per definitivo. Le scelte fatte qui, perche' chi rivede
 * sappia cosa sta toccando:
 *
 * - Si da' del TU, sempre, come in italiano: il programma e' pensato per bambini e
 *   principianti.
 * - Nessun accordo che dipenda da chi gioca. E' la stessa regola dell'italiano (niente
 *   "ti sei difeso/a"), e in francese colpisce il passato con "etre" ("tu t'es trompe'")
 *   e gli aggettivi riferiti a te ("tu es mieux place'"). Si riformula — "ta position
 *   est meilleure", "tu as bien resiste'" — invece di scrivere "place'·e", che per un
 *   bambino e' illeggibile. Gli accordi al FEMMINILE per la Nonna invece restano: lei e'
 *   sempre lei ("je me suis trompee", "tu m'as battue").
 * - La Nonna si chiama "Mamie": corto, affettuoso, capito ovunque. Nella Svizzera romanda
 *   si dice anche "Grand-maman": e' la prima domanda da fare a chi rivede.
 * - Pezzi con la maiuscola come in italiano (Roi, Dame, Tour, Fou, Cavalier), pedone
 *   minuscolo. Oltre alla coerenza aiuta i bambini: "fou" e "tour" sono anche parole
 *   comuni, e la maiuscola dice che qui sono pezzi.
 * - "aspettativa di vittoria" diventa "esperance de gain": non e' una probabilita', e
 *   una patta conta mezza partita.
 * - Tipografia francese: uno spazio prima di ? ! : ; e del %. E' lo spazio stretto che
 *   non va a capo (U+202F), cosi' il punto interrogativo non finisce da solo sulla riga
 *   dopo. Scritto come `${NB}` per non lasciare nel file un carattere invisibile.
 */
